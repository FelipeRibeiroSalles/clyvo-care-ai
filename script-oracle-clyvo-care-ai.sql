-- =====================================================
-- CURSOR PETS EM RISCO
-- =====================================================

DECLARE

    CURSOR C_PETS_RISCO IS

        SELECT
            P.NOME_PET,
            S.SCORE_RISCO,
            S.CLASSIFICACAO
        FROM TB_PETS P
        INNER JOIN TB_SCORE_RISCO_PETS S
            ON P.ID_PET = S.ID_PET
        WHERE S.CLASSIFICACAO IN ('ALTO', 'CRITICO');

BEGIN

    FOR V_REGISTRO IN C_PETS_RISCO LOOP

        DBMS_OUTPUT.PUT_LINE(
            'PET: ' || V_REGISTRO.NOME_PET ||
            ' | SCORE: ' || V_REGISTRO.SCORE_RISCO ||
            ' | CLASSIFICAÇÃO: ' || V_REGISTRO.CLASSIFICACAO
        );

    END LOOP;

END;
/

-- =====================================================
-- VIEWS
-- =====================================================

CREATE OR REPLACE VIEW VW_PETS_RISCO AS

SELECT
    P.NOME_PET,
    S.SCORE_RISCO,
    S.CLASSIFICACAO
FROM TB_PETS P
INNER JOIN TB_SCORE_RISCO_PETS S
    ON P.ID_PET = S.ID_PET
WHERE S.CLASSIFICACAO IN ('ALTO', 'CRITICO');

CREATE OR REPLACE VIEW VW_VACINAS_ATRASADAS AS

SELECT
    P.NOME_PET,
    V.NOME_VACINA,
    V.PROXIMA_DOSE
FROM TB_PETS P
INNER JOIN TB_VACINAS V
    ON P.ID_PET = V.ID_PET
WHERE V.STATUS = 'ATRASADA';

CREATE OR REPLACE VIEW VW_CONSULTAS_RETORNO AS

SELECT
    P.NOME_PET,
    C.DATA_CONSULTA,
    C.RETORNO_RECOMENDADO
FROM TB_CONSULTAS C
INNER JOIN TB_PETS P
    ON P.ID_PET = C.ID_PET
WHERE C.RETORNO_RECOMENDADO >= SYSDATE;

