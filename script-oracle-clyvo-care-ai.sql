-- =====================================================
-- TRIGGER CLASSIFICAR RISCO
-- =====================================================

CREATE OR REPLACE TRIGGER TRG_CLASSIFICAR_RISCO

BEFORE INSERT ON TB_SCORE_RISCO_PETS

FOR EACH ROW

BEGIN

    :NEW.CLASSIFICACAO :=
        FN_CLASSIFICAR_RISCO(:NEW.SCORE_RISCO);

END;
