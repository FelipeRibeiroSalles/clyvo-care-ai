CREATE OR REPLACE PROCEDURE REGISTRAR_LOG_ERRO (
    P_NOME_PROCEDURE IN VARCHAR2,
    P_CODIGO_ERRO IN NUMBER,
    P_MENSAGEM_ERRO IN VARCHAR2
)
IS
BEGIN

    INSERT INTO TB_LOG_ERRO (
        NOME_PROCEDURE,
        USUARIO_BANCO,
        DATA_ERRO,
        CODIGO_ERRO,
        MENSAGEM_ERRO
    )
    VALUES (
        P_NOME_PROCEDURE,
        USER,
        SYSDATE,
        P_CODIGO_ERRO,
        P_MENSAGEM_ERRO
    );

END;
/

-- =====================================================
-- FUNCTION IDADE PET
-- =====================================================

CREATE OR REPLACE FUNCTION FN_IDADE_PET (
    P_ID_PET IN NUMBER
)
RETURN NUMBER
IS

    V_IDADE NUMBER;

BEGIN

    SELECT FLOOR(
        MONTHS_BETWEEN(
            SYSDATE,
            DATA_NASCIMENTO_PET
        ) / 12
    )
    INTO V_IDADE
    FROM TB_PETS
    WHERE ID_PET = P_ID_PET;

    RETURN V_IDADE;

EXCEPTION

    WHEN OTHERS THEN

        REGISTRAR_LOG_ERRO(
            'FN_IDADE_PET',
            SQLCODE,
            SQLERRM
        );

        RETURN NULL;

END;
/

-- =====================================================
-- FUNCTION CLASSIFICAR RISCO
-- =====================================================

CREATE OR REPLACE FUNCTION FN_CLASSIFICAR_RISCO (
    P_SCORE IN NUMBER
)
RETURN VARCHAR2
IS

    V_CLASSIFICACAO VARCHAR2(20);

BEGIN

    IF P_SCORE <= 25 THEN
        V_CLASSIFICACAO := 'BAIXO';

    ELSIF P_SCORE <= 50 THEN
        V_CLASSIFICACAO := 'MODERADO';

    ELSIF P_SCORE <= 75 THEN
        V_CLASSIFICACAO := 'ALTO';

    ELSE
        V_CLASSIFICACAO := 'CRITICO';
    END IF;

    RETURN V_CLASSIFICACAO;

END;
/

-- =====================================================
-- TRIGGER ALERTA VACINA
-- =====================================================

CREATE OR REPLACE TRIGGER TRG_ALERTA_VACINA_ATRASADA

AFTER INSERT ON TB_VACINAS

FOR EACH ROW

BEGIN

    IF :NEW.STATUS = 'ATRASADA' THEN

        INSERT INTO TB_ALERTAS (
            TIPO_ALERTA,
            MENSAGEM,
            PRIORIDADE,
            STATUS,
            ID_PET
        )
        VALUES (
            'Vacina atrasada',
            'Vacina vencida detectada automaticamente.',
            'ALTA',
            'ATIVO',
            :NEW.ID_PET
        );

    END IF;

END;
/

