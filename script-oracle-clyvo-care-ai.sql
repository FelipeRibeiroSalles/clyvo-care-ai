-- =====================================================

CREATE TABLE TB_PETS (

    ID_PET NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    NOME_PET VARCHAR2(80) NOT NULL,

    ESPECIE VARCHAR2(40) NOT NULL,

    RACA VARCHAR2(60),

    SEXO CHAR(1) NOT NULL,

